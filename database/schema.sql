-- ---------------------------------------------------------------
-- 1. GAME MODES  (lookup / seed table)
-- ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.game_modes (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text   NOT NULL UNIQUE
);

-- Seed default modes
INSERT INTO public.game_modes (name) VALUES
    ('Marathon'),
    ('Sprint'),
    ('Ultra')
ON CONFLICT (name) DO NOTHING;

-- ---------------------------------------------------------------
-- 2. LEADERBOARD SCORES
-- ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.leaderboard_scores (
    id             bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_name    text        NOT NULL,
    score          bigint      NOT NULL CHECK (score >= 0),
    lines_cleared  int         NOT NULL CHECK (lines_cleared >= 0),
    level_reached  int         NOT NULL CHECK (level_reached >= 1),
    mode_id        bigint      NOT NULL REFERENCES public.game_modes (id),
    deleted_at     timestamptz,                          -- nullable: soft-delete sentinel
    created_at     timestamptz NOT NULL DEFAULT now()
);

-- Index for fast top-N queries
CREATE INDEX IF NOT EXISTS idx_leaderboard_scores_score_desc
    ON public.leaderboard_scores (score DESC);

-- ---------------------------------------------------------------
-- 3. PERMISSIONS  –  anon role (used by Supabase's public API key)
-- ---------------------------------------------------------------
GRANT SELECT, INSERT, UPDATE, DELETE
    ON public.game_modes, public.leaderboard_scores
    TO anon;

-- ---------------------------------------------------------------
-- 4. ROW LEVEL SECURITY
-- ---------------------------------------------------------------

-- game_modes
ALTER TABLE public.game_modes ENABLE ROW LEVEL SECURITY;

CREATE POLICY "anon_select_game_modes"
    ON public.game_modes FOR SELECT TO anon USING (true);

CREATE POLICY "anon_insert_game_modes"
    ON public.game_modes FOR INSERT TO anon WITH CHECK (true);

CREATE POLICY "anon_update_game_modes"
    ON public.game_modes FOR UPDATE TO anon USING (true) WITH CHECK (true);

CREATE POLICY "anon_delete_game_modes"
    ON public.game_modes FOR DELETE TO anon USING (true);

-- leaderboard_scores
ALTER TABLE public.leaderboard_scores ENABLE ROW LEVEL SECURITY;

CREATE POLICY "anon_select_leaderboard_scores"
    ON public.leaderboard_scores FOR SELECT TO anon USING (true);

CREATE POLICY "anon_insert_leaderboard_scores"
    ON public.leaderboard_scores FOR INSERT TO anon WITH CHECK (true);

CREATE POLICY "anon_update_leaderboard_scores"
    ON public.leaderboard_scores FOR UPDATE TO anon USING (true) WITH CHECK (true);

CREATE POLICY "anon_delete_leaderboard_scores"
    ON public.leaderboard_scores FOR DELETE TO anon USING (true);
